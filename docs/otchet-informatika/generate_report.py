def set_run_font(run, size=14, bold=False, italic=False, all_caps=False):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)
    if all_caps:
        run.font.all_caps = True


def set_paragraph_format(
    p,
    *,
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    first_line=1.25,
    space_before=0,
    space_after=0,
    line=1.5,
    keep_with_next=False,
):
    pf = p.paragraph_format
    pf.alignment = align
    pf.first_line_indent = Cm(first_line) if first_line else Cm(0)
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.line_spacing = line
    pf.keep_with_next = keep_with_next


def add_text(p, text, **kwargs):
    run = p.add_run(text)
    set_run_font(run, **kwargs)
    return run


def body(doc, text, *, first_line=1.25, space_before=0, space_after=0, bold=False, italic=False):
    p = doc.add_paragraph()
    set_paragraph_format(
        p,
        first_line=first_line,
        space_before=space_before,
        space_after=space_after,
    )
    add_text(p, text, bold=bold, italic=italic)
    return p


def heading(doc, text, level=1, *, new_page=False):
    if new_page:
        doc.add_page_break()
    p = doc.add_paragraph()
    set_paragraph_format(
        p,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        first_line=0,
        space_before=12,
        space_after=12,
        keep_with_next=True,
    )
    add_text(p, text.upper() if level == 1 else text, size=14, bold=True)
    return p


def question(doc, number, text):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=1.25, space_before=10, space_after=4, keep_with_next=True)
    add_text(p, f"Вопрос {number}. {text}", bold=True)
    return p


def answer(doc, text):
    return body(doc, text, space_after=2)


def center_line(doc, text, *, size=14, bold=False, italic=False, space_before=0, space_after=0, first_line=0):
    p = doc.add_paragraph()
    set_paragraph_format(
        p,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        first_line=first_line,
        space_before=space_before,
        space_after=space_after,
    )
    add_text(p, text, size=size, bold=bold, italic=italic)
    return p


def right_block(doc, lines, space_before=0):
    first = True
    for line in lines:
        p = doc.add_paragraph()
        set_paragraph_format(
            p,
            align=WD_ALIGN_PARAGRAPH.LEFT,
            first_line=0,
            space_before=space_before if first else 0,
            space_after=0,
        )
        p.paragraph_format.left_indent = Cm(9)
        add_text(p, line)
        first = False


def add_page_number(section):
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    set_run_font(run, size=12)

    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run._r.append(fld1)
    run._r.append(instr)
    run._r.append(fld2)


def setup_document():
    doc = Document()
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(3.0)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.different_first_page_header_footer = True
    add_page_number(section)

    style = doc.styles["Normal"]
    style.font.name = FONT
    style.font.size = Pt(14)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    style.paragraph_format.line_spacing = 1.5
    return doc


